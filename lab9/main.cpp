#include <iostream>
using namespace std;

int main()
{
  int x, y, z; // три целых числа
  int choice;  // номер выбранного способа
  int Max;     // переменная для хранения максимума

  // Ввод трех чисел
  cout << "Введите три целых числа x, y, z: ";
  cin >> x >> y >> z;

  // Выбор способа решения
  cout << "Выберите способ решения (1-4): ";
  cin >> choice;

  // Оператор выбора способа решения
  switch (choice)
  {
  // ===== Способ 1 =====
  // Используются вложенные полные ветвления
  case 1:
    if (x > y)
    {
      if (x > z)
        Max = x;
      else
        Max = z;
    }
    else
    {
      if (y > z)
        Max = y;
      else
        Max = z;
    }
    cout << "Максимальное число (способ 1): " << Max << endl;
    // break;

  // ===== Способ 2 =====
  // Используются неполные ветвления и логические выражения
  case 2:
    if (x >= y && x >= z)
      Max = x;
    if (y >= x && y >= z)
      Max = y;
    if (z >= x && z >= y)
      Max = z;

    cout << "Максимальное число (способ 2): " << Max << endl;
    // break;

  // ===== Способ 3 =====
  // Сначала максимум из x и y, затем сравнение с z
  case 3:
    if (x > y)
      Max = x;
    else
      Max = y;

    if (z > Max)
      Max = z;

    cout << "Максимальное число (способ 3): " << Max << endl;
    // break;

  // ===== Способ 4 =====
  // Используется условная арифметическая операция (?:)
  case 4:
    Max = (x > y) ? x : y;     // максимум из x и y
    Max = (Max > z) ? Max : z; // сравнение с z

    cout << "Максимальное число (способ 4): " << Max << endl;
    // break;

  // Если введён неверный номер способа
  default:
    cout << "Ошибка: выбран неверный способ решения!" << endl;
  }

  return 0; // завершение программы
}